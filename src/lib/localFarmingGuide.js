export const GUIDE_FIELDS = [
  ['purpose', '작업 목적'], ['preparation', '준비 사항'], ['procedure', '수행 순서'],
  ['checks', '확인 항목'], ['evidence', '사진·기록 안내'],
]
export function guideTasks(stage) {
  return structuredClone(stage.tasks ?? TEMPLATES[stage.code] ?? [])
}
// Enrich legacy plans without changing saved notes, IDs, dates or report snapshots.
export function withDetailedGuide(plan) {
  return { ...structuredClone(plan), stages: plan.stages.map(stage => ({ ...structuredClone(stage), tasks: guideTasks(stage) })) }
}
